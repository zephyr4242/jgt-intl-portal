export function loadLocale () {
  try {
    const raw = localStorage.getItem(LANG_STORAGE_KEY)
    if (raw && MESSAGES[raw]) return raw
  } catch (e) { /* ignore */ }
  return 'zh-Hans'
}

export function saveLocale (locale) {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, locale)
  } catch (e) { /* ignore */ }
  try {
    document.documentElement.setAttribute('lang', locale === 'en' ? 'en' : (locale === 'zh-Hant' ? 'zh-Hant' : 'zh-Hans'))
  } catch (e) { /* ignore */ }
}

export function t (locale, key, params) {
  const pack = MESSAGES[locale] || MESSAGES['zh-Hans']
  let text = pack[key] || MESSAGES['zh-Hans'][key] || key
  if (params && typeof params === 'object' && typeof text === 'string') {
    Object.keys(params).forEach(k => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), params[k] == null ? '' : String(params[k]))
    })
  }
  return text
}
